/// Delegate that tells Flutter how to create/load an AppLocalizations
/// instance for the currently selected Locale.
class _AppLocalizationsDelegate extends LocalizationsDelegate<AppLocalizations> {
  const _AppLocalizationsDelegate();

  @override
  bool isSupported(Locale locale) {
    // We support every language code we ship translations for, regardless
    // of the region/script suffix (e.g. 'ar_SA' still resolves to 'ar').
    return AppLocalizations._translations.keys
        .map((c) => c.split('_').first)
        .contains(locale.languageCode);
  }

  @override
  Future<AppLocalizations> load(Locale locale) async {
    return AppLocalizations(locale);
  }

  @override
  bool shouldReload(_AppLocalizationsDelegate old) => false;
}
